"""Plan and install profile-local cron wrappers through the supported Hermes CLI.

Planning is pure: dry-run does not create directories, wrappers, state, or jobs.
Jobs resolve their assigned ids by their unique names at runtime, so a wrapper
can safely be attached at creation while the new job remains paused.
"""
from __future__ import annotations

import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from .settings import Settings, hermes_root, read_settings_file

PLUGIN_ROOT = Path(__file__).resolve().parents[1]
PROFILE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$")
# The review hook and the Telegram buttons read answers only in a chat topic, so a target names both.
TARGET_RE = re.compile(r"^telegram:-?\d+:\d+$")


def profile_home(profile: str) -> Path:
    if not PROFILE_RE.fullmatch(profile) or profile in (".", ".."):
        raise ValueError("invalid profile name")
    root = hermes_root()
    return (root if profile == "default" else root / "profiles" / profile).resolve()


def read_settings() -> tuple[Settings, str | None]:
    """Same settings contract as load_settings, without its directory-creation side effect."""
    override = os.environ.get("HERMES_INITIATIVES_DATA_DIR", "").strip()
    path = (Path(override) if override else hermes_root() / "plugin-data/initiatives") / "settings.json"
    if not path.exists():
        return Settings(), f"settings file does not exist: {path}"
    return read_settings_file(path)


def read_jobs(home: Path) -> list[dict]:
    path = home / "cron/jobs.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    jobs = data if isinstance(data, list) else data.get("jobs", [])
    if not isinstance(jobs, list):
        raise ValueError(f"invalid cron job list: {path}")
    return jobs


def job_name(project: str, kind: str) -> str:
    return f"initiatives:{project}:{kind}"


@dataclass(frozen=True)
class JobPlan:
    kind: str
    name: str
    profile: str
    home: Path
    project: str
    board: str
    schedule: str
    prompt: str
    cwd: Path
    timezone: str
    policy_skill: str | None
    recovery_name: str | None
    existing_id: str | None = None
    python: str = sys.executable
    plugin_root: Path = PLUGIN_ROOT
    data_root: Path | None = None

    @property
    def prefix(self) -> list[str]:
        return ["hermes", "-p", self.profile, "cron"]

    @property
    def wrapper_path(self) -> Path:
        return self.home / "scripts" / f"initiatives-{self.project}-{self.kind}.sh"

    @property
    def gates_path(self) -> Path:
        # Per-project lists: two projects must never overwrite each other's human gates.
        return (self.data_root or self.home / "plugin-data/initiatives") / "review-work" / self.project / "gates.json"

    def wrapper(self, own_job: str | None = None, recovery_job: str | None = None) -> str:
        scripts = {"recovery": "kanban_recovery_wake_gate.py", "review": "initiatives_review_wake_gate.py",
                   "merge-gate": "deep_merge_gate_filer.py"}
        args = [str(self.plugin_root.resolve() / "autonomy" / scripts[self.kind]), "--project", self.project]
        if self.kind != "merge-gate":
            args += ["--board", self.board, "--job", own_job or f"name:{self.name}"]
        if self.kind == "recovery":
            args += ["--self-author", self.profile, "--no-review-queue", "--recovery-signals", "--max-quiet-hours", "3"]
        elif self.kind == "review":
            args += ["--gates-json", str(self.gates_path)]
            if self.recovery_name:
                args += ["--recovery-job", recovery_job or f"name:{self.recovery_name}"]
        lines = ["#!/usr/bin/env bash", "# Generated by hermes initiatives setup; keep this file inside this profile's scripts/.",
                 "set -euo pipefail", f"export HERMES_HOME={shlex.quote(str(self.home))}"]
        if self.data_root is not None:
            lines += [f"export HERMES_INITIATIVES_DATA_DIR={shlex.quote(str(self.data_root))}"]
        lines += ["exec env -u PYTHONPATH " + shlex.join([str(Path(self.python).absolute()), *args]) + ' "$@"']
        return "\n".join(lines) + "\n"

    @property
    def create_command(self) -> list[str] | None:
        if self.existing_id:
            return None
        cmd = [*self.prefix, "create", "--name", self.name, "--deliver", "local", "--failure-deliver", "local",
               "--paused", "--script", self.wrapper_path.name, "--workdir", str(self.cwd)]
        if self.timezone:
            cmd += ["--timezone", self.timezone]
        if self.kind == "merge-gate":
            cmd += ["--no-agent"]
        else:
            cmd += ["--skill", "initiatives:kanban-sdlc-orchestration" if self.kind == "recovery" else "initiatives:initiatives"]
            if self.kind == "review":
                cmd += ["--skill", "initiatives:kanban-human-gates"]
            if self.policy_skill:
                cmd += ["--skill", self.policy_skill]
        return [*cmd, self.schedule, self.prompt]


def build_plan(settings: Settings, project_id: str, profile: str, *, home: Path | None = None,
               existing: list[dict] | None = None,
               recovery: bool = True, merge_gate: bool = True,
               schedule_review: str = "15,45 * * * *", schedule_recovery: str = "*/30 * * * *",
               plugin_root: Path = PLUGIN_ROOT, python: str | None = None) -> list[JobPlan]:
    project = settings.project(project_id)
    if not project or not project.kanban_board:
        raise ValueError("project must exist and have kanban_board configured")
    if not PROFILE_RE.fullmatch(profile) or profile in (".", ".."):
        raise ValueError("invalid profile name")
    home = (home or profile_home(profile)).expanduser().resolve()
    existing = existing if existing is not None else read_jobs(home)
    target = settings.review_target or ""
    if target and not TARGET_RE.fullmatch(target):
        raise ValueError("settings review_target must be telegram:<chat>:<topic>")
    cwd = (project.cwd or project.root).expanduser().resolve()
    override = os.environ.get("HERMES_INITIATIVES_DATA_DIR", "").strip()
    data_root = (Path(override) if override else hermes_root() / "plugin-data/initiatives").expanduser().resolve()
    work = data_root / "review-work" / project_id
    values = dict(profile=profile, board=project.kanban_board, project=project_id,
                  scripts_dir=str(plugin_root / "skills/initiatives/scripts"), work_dir=str(work),
                  gate_list_path=str(work / "gates.json"), review_target=target or "(not configured; do not notify)",
                  policy_skill=project.policy_skill or "(none configured; use bundled defaults)", workdir=str(cwd),
                  review_tick=str(plugin_root / "skills/initiatives/references/review_tick.md"))
    kinds = (["recovery"] if recovery else []) + ["review"] + (["merge-gate"] if merge_gate and project.merge_reviewer else [])
    result = []
    for kind in kinds:
        name = job_name(project_id, kind)
        matches = [j for j in existing if j.get("name") == name]
        if len(matches) > 1:
            raise ValueError(f"duplicate cron job name {name!r}; reconcile manually")
        prompt = "" if kind == "merge-gate" else (plugin_root / "autonomy/prompts" / f"{kind}.md").read_text().format(**values)
        result.append(JobPlan(kind, name, profile, home, project_id, project.kanban_board,
                              schedule_recovery if kind == "recovery" else schedule_review if kind == "review" else "*/2 * * * *",
                              prompt, cwd, settings.timezone, project.policy_skill,
                              job_name(project_id, "recovery") if recovery else None,
                              str(matches[0]["id"]) if matches else None, python or sys.executable,
                              plugin_root.resolve(), data_root))
    return result


def _run(command: list[str], home: Path) -> subprocess.CompletedProcess:
    env = {**os.environ, "HERMES_HOME": str(home)}
    env.pop("PYTHONPATH", None)
    return subprocess.run(command, env=env, capture_output=True, text=True, timeout=120, check=True)


def execute_plan(plans: list[JobPlan], *, dry_run: bool = False, runner=None) -> None:
    """Never mutate existing named jobs; failures leave newly-created jobs paused for inspection."""
    runner = runner or _run
    for plan in plans:
        if plan.existing_id:
            presence = 'present' if plan.wrapper_path.is_file() else 'MISSING'
            print(f"EXISTS {plan.name}: {plan.existing_id} (wrapper {presence}); unchanged")
            continue
        create_command = plan.create_command
        assert create_command is not None
        if dry_run:
            print(f"WRITE {plan.wrapper_path}\n{plan.wrapper()}", end="")
            print(shlex.join(create_command))
            marker = f"<id:{plan.name}>"
            print(shlex.join([*plan.prefix, "edit", marker, "--script", plan.wrapper_path.name]))
            print(shlex.join([*plan.prefix, "resume", marker]))
            continue
        # Recheck inside a profile-local lock; two concurrent setup processes must not duplicate names.
        import fcntl

        plan.home.mkdir(parents=True, exist_ok=True)
        with (plan.home / ".initiatives-setup.lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            if any(j.get("name") == plan.name for j in read_jobs(plan.home)):
                print(f"EXISTS {plan.name}; unchanged")
                continue
            scripts = plan.home / "scripts"
            scripts.mkdir(parents=True, exist_ok=True)
            if scripts.is_symlink() or scripts.resolve() != scripts:
                raise ValueError(f"scripts directory must be inside profile home: {scripts}")
            if plan.wrapper_path.is_symlink():
                raise ValueError(f"refusing symlink wrapper: {plan.wrapper_path}")
            if plan.wrapper_path.exists() and plan.wrapper_path.read_text() != plan.wrapper():
                raise ValueError(f"refusing to overwrite a different wrapper: {plan.wrapper_path}")
            plan.wrapper_path.write_text(plan.wrapper(), encoding="utf-8")
            plan.wrapper_path.chmod(0o700)
            proc = runner(create_command, plan.home)
            match = re.search(r"Created job:\s*([A-Za-z0-9_-]+)", proc.stdout)
            matches = [j for j in read_jobs(plan.home) if j.get("name") == plan.name]
            if len(matches) != 1 or (match and str(matches[0]["id"]) != match.group(1)):
                raise RuntimeError(f"could not read back unique created job {plan.name}; inspect paused job")
            jid = str(matches[0]["id"])
            runner([*plan.prefix, "edit", jid, "--script", plan.wrapper_path.name], plan.home)
            runner([*plan.prefix, "resume", jid], plan.home)
            print(f"CREATED {plan.name}: {jid}; wrapper {plan.wrapper_path}")


def status(profile: str) -> list[dict]:
    home = profile_home(profile)
    return [{"profile": profile, "id": j.get("id"), "name": j.get("name"), "enabled": j.get("enabled"),
             "script": j.get("script"), "wrapper_exists": bool(j.get("script")) and (home / "scripts" / j["script"]).is_file()}
            for j in read_jobs(home) if str(j.get("name", "")).startswith("initiatives:")]


def doctor(project_id: str | None = None) -> list[str]:
    settings, error = read_settings()
    errors = [error] if error else []
    if not shutil.which("hermes"):
        errors.append("hermes is not on PATH")
    target = settings.review_target
    if not target:
        errors.append("review_target is unset: decisions show in the UI only (no Telegram push or answers)")
    elif not TARGET_RE.fullmatch(target):
        errors.append("review_target must be telegram:<chat>:<topic>")
    projects = [settings.project(project_id)] if project_id else settings.projects
    if not projects:
        errors.append("settings has no projects")
    for project in projects:
        if project is None:
            errors.append(f"unknown project: {project_id}")
            continue
        if not project.policy_skill:
            errors.append(f"{project.id}: policy_skill is unset (bundled defaults only)")
        if not project.worker_profiles:
            errors.append(f"{project.id}: worker_profiles is empty (worker comments cannot be filtered)")
        if not project.kanban_board:
            errors.append(f"{project.id}: kanban_board is unset")
        else:
            from autonomy.config import board_path

            try:
                if not board_path(project.kanban_board).is_file():
                    errors.append(f"{project.id}: board {project.kanban_board!r} does not exist")
            except (ValueError, ImportError) as exc:
                errors.append(f"{project.id}: board check failed: {exc}")
    return errors
